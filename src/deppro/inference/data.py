"""
Parquet Data Loading for MLX Training
=====================================

Loads (I_obs, D_true) pairs from Parquet files generated by the Dstk simulator.
"""

from pathlib import Path
from typing import Iterator, Tuple

import numpy as np

try:
    import mlx.core as mx
    HAS_MLX = True
except ImportError:
    HAS_MLX = False


class ParquetDataset:
    """Streaming Parquet dataset for MLX training.

    Loads entire dataset into memory (< 1GB for 1M samples),
    yields shuffled mini-batches as MLX arrays.

    Parameters
    ----------
    path : str or Path
        Path to Parquet file from Dstk simulator.
    batch_size : int
        Mini-batch size.
    shuffle : bool
        Shuffle data each epoch.
    seed : int
        RNG seed for reproducible shuffling.
    """

    def __init__(
        self,
        path: str,
        batch_size: int = 8192,
        shuffle: bool = True,
        seed: int = 42,
    ):
        import pyarrow.parquet as pq

        self.batch_size = batch_size
        self.shuffle = shuffle
        self.rng = np.random.default_rng(seed)

        # Load entire dataset into memory
        table = pq.read_table(str(path))
        self.n_samples = table.num_rows

        # Convert FixedSizeList columns to numpy
        self.I_obs = np.array(table['I_obs'].to_pylist(), dtype=np.float32)
        self.D_true = np.array(table['D_true'].to_pylist(), dtype=np.float32)
        self.thickness = np.array(
            table['thickness'].to_pylist(), dtype=np.float32
        )
        self.abruptness = np.array(
            table['abruptness'].to_pylist(), dtype=np.float32
        )

        self.input_dim = self.I_obs.shape[1]
        self.output_dim = self.D_true.shape[1]

    def __len__(self) -> int:
        return (self.n_samples + self.batch_size - 1) // self.batch_size

    def __iter__(self) -> Iterator[Tuple]:
        """Yield (I_obs_batch, D_true_batch) as MLX arrays."""
        indices = np.arange(self.n_samples)
        if self.shuffle:
            self.rng.shuffle(indices)

        for start in range(0, self.n_samples, self.batch_size):
            end = min(start + self.batch_size, self.n_samples)
            idx = indices[start:end]
            yield (
                mx.array(self.I_obs[idx]),
                mx.array(self.D_true[idx]),
            )

    @property
    def n_batches(self) -> int:
        return len(self)
